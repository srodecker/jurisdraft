// Writes docs/forms-v2/FIELD-NAMING.md from the fact dictionary, formats and conditions,
// so the naming reference always matches the code.  node scripts/forms-v2-reference.js
const fs = require('fs');
const path = require('path');
const { FACTS, CONDITIONS, buildContext } = require('../lib/forms/dictionary');
const { FORMATS } = require('../lib/forms/formatters');

const sample = buildContext({
    matter: { debtorName: 'Erick Alonso Acevedo', debtorAddress: '123 MAIN ST', debtorCity: 'BAKERSFIELD', debtorState: 'CA', debtorZip: '93301', creditorName: 'Kinecta Federal Credit Union', caseNumber: '25CLB01343', courtCounty: 'Kern', courtBranch: 'Metropolitan Division', courtAddress: '1215 Truxtun Avenue, Bakersfield, CA 93301', demandAmount: '18450.22', costs: '435', dates: { complaintFiled: '2025-10-28', served: '2026-03-17' } },
    profile: { firm: { name: 'WRIGHT, FINLAY & ZAK, LLP', address: '4665 MacArthur Court, Suite 200', city: 'Newport Beach', state: 'CA', zip: '92660', phone: '(949) 477-5050' }, attorneys: [{ name: 'Gwen H. Ribar', sbn: '188024', email: 'gribar@example.com' }, { name: 'Sabaa Ghomashchi', sbn: '352285', email: 'sg@example.com' }] },
    today: new Date(Date.UTC(2026, 9, 15))
});
const show = v => (v && typeof v === 'object' ? JSON.stringify(v).slice(0, 80) : String(v ?? '')).replace(/\|/g, '\\|').replace(/\n/g, ' ⏎ ');
const examples = {
    UPPER: 'COURT_COUNTY', TITLE: 'FIRM_NAME', LONG: 'COMPLAINT_FILED', SHORT: 'COMPLAINT_FILED', MDY: 'COMPLAINT_FILED', MDYY: 'COMPLAINT_FILED',
    MONEY: 'DEMAND_AMOUNT', DOLLARS: 'DEMAND_AMOUNT', PLAIN: 'COSTS', WORDS: null, LAST4: null, NAME: 'DEFENDANT', ET_AL: 'DEFENDANT', INDIVIDUAL: 'DEFENDANT',
    DOES: 'DEFENDANT', WITH_ROLE: 'PLAINTIFF', STREET: 'DEFENDANT_ADDRESS', CITY_STATE_ZIP: 'DEFENDANT_ADDRESS', ONE_LINE: 'DEFENDANT_ADDRESS',
    NAME_ADDRESS: 'DEFENDANT_ADDRESS', INDIVIDUAL_ADDRESS: 'DEFENDANT_ADDRESS', SERVICE_LINE: 'DEFENDANT_ADDRESS', NAME_SBN: 'ATTORNEYS',
    NAME_SBN_COLON: 'ATTORNEY_2', ESQ: 'ATTORNEY_2', EMAILS: 'ATTORNEYS', NAMES: 'ATTORNEYS', BOLD: null
};
const lines = [
    '# Form field naming standard (forms v2)', '',
    '_Generated by `node scripts/forms-v2-reference.js` — do not edit by hand._', '',
    '## How to name a field', '',
    '| Field name | What goes in |', '|---|---|',
    '| `[FACT]` | the fact; dates/amounts follow the field\'s own Acrobat format if it has one |',
    '| `[FACT:FORMAT]` | the fact through a format, e.g. `[DEFENDANT:ET_AL]` |',
    '| `[FACT:FORMAT:FORMAT]` | formats applied left to right, e.g. `[COURT_COUNTY:UPPER:BOLD]` |',
    '| `[CHECK:CONDITION]` | checkbox, ticked when the condition is true |',
    '| `[MANUAL:any_label]` | never filled automatically — you or the AI fill it per form |',
    '| `[PRESET:any_label]` | left exactly as saved in the template (pre-checked boxes, defaults) |',
    '| `…#p2`, `…#2` | suffix is ignored, so the same fact can sit in two separate fields |', '',
    'Tip: in Acrobat, fields with exactly the same name share one value — name both page captions `[CASE_NUMBER]` and they fill together.', '',
    '## Facts', '', '| Fact | Meaning | Type | Example value |', '|---|---|---|---|',
    ...Object.values(FACTS).map(f => `| \`${f.key}\` | ${f.label}${f.extract ? ` — ${f.extract}` : ''} | ${f.type} | ${show(f.get(sample))} |`),
    '', '## Formats', '', '| Format | Example |', '|---|---|',
    ...Object.keys(FORMATS).map(k => { const ex = examples[k]; let out = ''; try { out = ex ? FORMATS[k](FACTS[ex].get(sample)) : { WORDS: FORMATS.WORDS('1'), LAST4: FORMATS.LAST4('123-45-6789'), BOLD: '(draws the text in bold)' }[k]; } catch (e) { out = ''; } return `| \`${k}\` | ${ex ? `\`[${ex}:${k}]\` → ` : ''}${show(out)} |`; }),
    '', '## Checkbox conditions', '', '| Condition | Ticked when |', '|---|---|',
    ...Object.entries(CONDITIONS).map(([k, c]) => `| \`CHECK:${k}\` | ${c.label} |`), ''
];
fs.mkdirSync(path.join(__dirname, '..', 'docs', 'forms-v2'), { recursive: true });
fs.writeFileSync(path.join(__dirname, '..', 'docs', 'forms-v2', 'FIELD-NAMING.md'), lines.join('\n'));
console.log('Wrote docs/forms-v2/FIELD-NAMING.md');
